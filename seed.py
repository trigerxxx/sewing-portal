def d(days: int = 0) -> str:
    return (date.today() - timedelta(days=days)).strftime("%d.%m.%Y")


def hours_ago(h: float) -> str:
    return (datetime.now() - timedelta(hours=h)).strftime("%d.%m.%Y %H:%M")


def dt(days: int, hour: int, minute: int = 0) -> str:
    day = date.today() - timedelta(days=days)
    return datetime(day.year, day.month, day.day, hour, minute).strftime("%d.%m.%Y %H:%M")


